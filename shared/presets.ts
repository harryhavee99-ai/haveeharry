export function getCaptionPreset(id: string): CaptionStyleConfig {
  const found = CAPTION_PRESETS.find((p) => p.id === id) ?? CAPTION_PRESETS[0];
  return { ...found.config };
}

export function getVisualStylePreset(id: string): ColorGradingConfig {
  const found = VISUAL_STYLE_PRESETS.find((p) => p.id === id) ?? VISUAL_STYLE_PRESETS[0];
  return { ...found.grading };
}

export function createDefaultFraming(
  aspectRatio: FramingConfig['aspectRatio'] = '9:16',
  mode: FramingConfig['mode'] = 'ai_auto'
): FramingConfig {
  return {
    aspectRatio,
    mode,
    manualX: 0.5,
    manualY: 0.5,
    zoom: 1.0,
    focalKeyframes: [],
  };
}

